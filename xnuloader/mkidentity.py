#!/usr/bin/env python3
"""Take the identity of an iPhone from its real device tree, for the loader to hand to XNU.

usage: mkidentity.py DeviceTree.<board>.bin > identity.h
       mkidentity.py --placeholder > identity.h
       mkidentity.py --blank > identity.h          a loader whose identity is filled in afterwards (--fill): no Apple data
       mkidentity.py --fill loader.efi DeviceTree.<board>.bin
                                                  the identity written into such a loader, on the user's own machine,
                                                  from their own IPSW: a prebuilt loader with nobody's identity in it

The input is the device tree itself, i.e. the payload of Firmware/all_flash/DeviceTree.<board>.im4p
of the IPSW, decompressed: "ipsw img4 im4p extract DeviceTree.d22ap.im4p -o DeviceTree.d22ap.bin".

Darwin user space (MobileGestalt above all) decides what device it runs on from the device
tree: the root node's model and compatible, and the /product node (screen class, artwork
scale, product name ...), and the /product/haptics node: what the phone's haptics are (MobileGestalt's
DeviceSupportsClosedLoopHaptics is its "closed-loop"; with it Darwin plays the system's vibrations and
feedbacks as waveforms on the actuator, and without it looks for an old vibration motor in IOKit,
which the iPhone X does not have), and of the /product/camera node what the phone here has as well (its
"flash": MobileGestalt's camera-flash, without which there is no flashlight in Control Center). The loader builds its own device tree for the hardware we really
have, but copies these properties from the device tree in the Darwin firmware so that the
system believes it is the iPhone its files were built for.

Properties that iBoot fills in on a real phone ("syscfg/..." placeholders: serial number,
colours, calibration data) are left out; the loader adds the few that are needed itself.
"""
import struct
import sys


def parse(data, pos=0):
    """One node of a flattened Apple device tree: (properties, children, next position)."""
    nprops, nchildren = struct.unpack_from('<II', data, pos)
    pos += 8
    props = []
    for _ in range(nprops):
        name = data[pos:pos + 32].split(b'\0')[0].decode()
        length = struct.unpack_from('<I', data, pos + 32)[0] & 0x7FFFFFFF
        value = data[pos + 36:pos + 36 + length]
        props.append((name, value))
        pos += 36 + (length + 3 & ~3)
    children = []
    for _ in range(nchildren):
        child, pos = parse(data, pos)
        children.append(child)
    return (props, children), pos


def name_of(node):
    return dict(node[0]).get('name', b'').split(b'\0')[0].decode()


def kept_props(props, skip):
    return [(n, v) for n, v in props if n not in skip and not v.startswith((b'syscfg/', b'macaddr/', b'zeroes/'))]


def emit(label, props, skip):
    kept = kept_props(props, skip)
    blob = bytearray()
    print(f'/* {len(kept)} properties */')
    print(f'static const struct identity_prop {label}[] = {{')
    for name, value in kept:
        print(f'\t{{ "{name}", {len(blob)}, {len(value)} }},')
        blob += value
    print('};')
    print(f'static const unsigned char {label}_data[] = {{')
    for i in range(0, len(blob), 20):
        print('\t' + ' '.join(f'0x{b:02x},' for b in blob[i:i + 20]))
    print('};\n')


def emit_empty(label):
    # A one-entry table whose single property has a name no device tree uses and a zero length:
    # dt_identity copies it as an empty, harmless property; dt_identity_one never matches it. This
    # avoids a zero-length array (not standard C) while carrying no Apple-derived data.
    print(f'/* placeholder: no properties (built without an IPSW) */')
    print(f'static const struct identity_prop {label}[] = {{ {{ "hakios-placeholder", 0, 0 }} }};')
    print(f'static const unsigned char {label}_data[] = {{ 0 }};\n')


def placeholder():
    """An identity.h with no Apple-derived data, for building the loader without an IPSW.

    The device-tree properties Darwin reads to tell which iPhone it is are left empty. This is
    enough to build and boot the open kernel under QEMU with an Apple-free user space (the
    `hello` RAM disk); it is NOT enough to run the Darwin 16.5 user space, which wants the real
    properties. Generate the real header from your own IPSW (mkidentity.sh) for that.
    """
    print('/* Generated by mkidentity.py --placeholder: no Apple device-tree data. */')
    print('struct identity_prop { const char *name; unsigned offset, length; };\n')
    for label in ('identity_root', 'identity_product', 'identity_haptics', 'identity_camera'):
        emit_empty(label)


# The four tables, and what of each node is not taken. Of the root: who we are; addresses, the phandle and what iBoot
# fills in stay ours. Of the camera the loader takes what the hardware here has (the flash so far).
SKIP_ROOT = ('name', '#address-cells', '#size-cells', 'AAPL,phandle', 'clock-frequency', 'platform-name', 'time-stamp',
             'secure-root-prefix')
SKIP_NODE = ('name', 'AAPL,phandle')


def tables(path):
    root, _ = parse(open(path, 'rb').read())
    children = {name_of(c): c for c in root[1]}
    product = {name_of(c): c for c in children['product'][1]}
    return (('identity_root', kept_props(root[0], SKIP_ROOT)),
            ('identity_product', kept_props(children['product'][0], SKIP_NODE)),
            ('identity_haptics', kept_props(product['haptics'][0], SKIP_NODE)),
            ('identity_camera', kept_props(product['camera'][0], SKIP_NODE)))


# The blank loader's identity: one structure of fixed size, found in the loader's file by its marker and filled in there.
# Names are kept in the entries (no pointers: the file is patched, not relinked); an entry with an empty name is no
# property (loader.c's dt_identity skips it). The structure is an ordinary global, neither const nor static, so that
# the compiler cannot take its zeros for constants and leave the tables out.
BLOB_MARK = b'HAKIOS-IDENTITY1'
BLOB_TABLES = (('identity_root', 32, 1024), ('identity_product', 128, 4096), ('identity_haptics', 16, 512),
               ('identity_camera', 96, 2048))
NAME = 32


def blank():
    print('/* Generated by mkidentity.py --blank: no Apple data. The identity is written into the built loader')
    print('   afterwards, from the user\'s own IPSW: mkidentity.py --fill loader.efi DeviceTree.d22ap.bin */')
    print(f'struct identity_prop {{ char name[{NAME}]; unsigned offset, length; }};\n')
    print('struct identity_blob {')
    print(f'\tchar mark[{len(BLOB_MARK)}];')
    for label, props, _ in BLOB_TABLES:
        print(f'\tstruct identity_prop {label[9:]}[{props}];')
    for label, _, data in BLOB_TABLES:
        print(f'\tunsigned char {label[9:]}_data[{data}];')
    print('};')
    mark = ', '.join(f"'{chr(c)}'" for c in BLOB_MARK)
    print(f'struct identity_blob identity_blob = {{ .mark = {{ {mark} }} }};')
    for label, _, _ in BLOB_TABLES:
        print(f'#define {label} (identity_blob.{label[9:]})')
        print(f'#define {label}_data (identity_blob.{label[9:]}_data)')


def fill(loader, path):
    image = bytearray(open(loader, 'rb').read())
    at = image.find(BLOB_MARK)
    if at < 0 or image.find(BLOB_MARK, at + 1) >= 0:
        sys.exit(f'mkidentity.py: {loader}: not a blank loader (its identity marker is {"missing" if at < 0 else "there twice"})')
    props_at = at + len(BLOB_MARK)
    data_at = props_at + sum(n * (NAME + 8) for _, n, _ in BLOB_TABLES)
    for (label, kept), (_, nprops, ndata) in zip(tables(path), BLOB_TABLES):
        blob = b''.join(v for _, v in kept)
        if len(kept) > nprops or len(blob) > ndata or any(len(n.encode()) >= NAME for n, _ in kept):
            sys.exit(f'mkidentity.py: {label}: {len(kept)} properties, {len(blob)} bytes: more than the blank loader holds')
        entries, offset = b'', 0
        for name, value in kept:
            entries += struct.pack(f'<{NAME}sII', name.encode(), offset, len(value))
            offset += len(value)
        image[props_at:props_at + nprops * (NAME + 8)] = entries.ljust(nprops * (NAME + 8), b'\0')
        image[data_at:data_at + ndata] = blob.ljust(ndata, b'\0')
        props_at += nprops * (NAME + 8)
        data_at += ndata
        print(f'mkidentity.py: {label}: {len(kept)} properties, {len(blob)} bytes', file=sys.stderr)
    image[at:at + len(BLOB_MARK)] = b'HAKIOS-IDENTITY.'     # filled: a second --fill is refused
    open(loader, 'wb').write(image)


def main():
    if len(sys.argv) > 1 and sys.argv[1] == '--placeholder':
        placeholder()
        return
    if len(sys.argv) > 1 and sys.argv[1] == '--blank':
        blank()
        return
    if len(sys.argv) > 3 and sys.argv[1] == '--fill':
        fill(sys.argv[2], sys.argv[3])
        return
    print('/* Generated by mkidentity.py from the device tree of the Darwin firmware. Do not edit. */')
    print('struct identity_prop { const char *name; unsigned offset, length; };\n')
    for label, kept in tables(sys.argv[1]):
        emit(label, kept, ())


if __name__ == '__main__':
    main()
